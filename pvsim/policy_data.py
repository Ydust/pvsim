# 3. 关键金属国产年产能 (tonnes/yr)
# ============================================================
# 来源 (USGS Mineral Commodity Summaries 2024, 工信部公开数据):
#   - Indium (铟):  中国 ~540-600 t/yr, 全球 ~900 t/yr → 中国占 ~67%
#   - Silver (银):  中国矿产银 ~3500 t/yr; 但 PV 用银主要靠工业回收+进口
#   - Lead (铅):    中国年产 ~4,500,000 t (远超 PV 需求量级, 不构成约束)
# 增长假设: In/Ag 国产产能温和增 1-2%/yr; Pb 暂不约束
def critical_metal_supply_t_per_yr():
    years = np.arange(2024, 2051)
    indium = 600 * 1.02 ** (years - 2024)        # +2%/yr
    silver = 3500 * 1.015 ** (years - 2024)      # +1.5%/yr
    return years, {"In": indium, "Ag": silver}


