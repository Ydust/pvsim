# 2. 中国电网年均排放因子 (kgCO2/kWh) 2024-2050
# ============================================================
# 来源:
#   - 生态环境部"中国电网平均排放因子" 2022: 0.5703 kgCO2/kWh
#   - IEA "Energy Technology Perspectives 2023" 中国情景:
#     2030 ~0.42, 2040 ~0.25, 2050 ~0.10 (基于 STEPS)
#   - "双碳"政策路径文献 (DRC 2023): 2060 接近 0
def china_grid_ef_kgco2_per_kwh():
    years = np.arange(2024, 2051)
    # 2024 ~0.55; 线性下降至 2050 0.10 (含部分加速段)
    ef = np.interp(years,
                   [2024, 2030, 2040, 2050],
                   [0.55, 0.42, 0.25, 0.10])
    return years, ef


