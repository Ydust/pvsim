# 1. 中国光伏在运目标 2024-2050 (GW)
# ============================================================
# 来源:
#   - 国家能源局 2024年新能源累计装机 (含光伏 887GW + 风电 521GW)
#   - 中国可再生能源学会光伏专委会"2024中国光伏行业发展路线图"
#   - IEA "Renewables 2024" 中国情景: 2030 ~1400GW, 2050 ~2400GW
#   - "30·60"双碳目标隐含 2030 风+光 1200GW, 2060 全国电力深度脱碳
# 说明: 2024 起以光伏装机为主线; 仅光伏目标
def china_pv_target_gw():
    """2024 实际 887 GW; 2030 1500 (IEA 路线图); 2040 2150; 2050 2400 (能源去化石极限)"""
    years = np.arange(2024, 2051)
    target = np.interp(years,
                       [2024, 2030, 2040, 2050],
                       [887,  1500, 2150, 2400])
    return years, target


