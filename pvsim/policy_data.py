# 7. 各技术成熟度: 年最大可获得份额 (上界)
# ============================================================
# 反映工业产能上量节奏。基于:
#   - 钙钛矿: GCL/纤纳/协鑫 2024-2025 GW级产能投产, 预计2030年前能达50%份额
#   - 叠层:  LONGi 33% 大面积 NREL 认证 2025; 预计 2030 后量产
def tech_max_share(tech_key, year):
    if tech_key == "晶硅25y":
        return 1.0
    if tech_key == "钙钛矿15y":
        return min(0.7, max(0, (year - 2024) / 5.0))
    if tech_key == "钙钛矿25y":
        return min(0.5, max(0, (year - 2030) / 5.0))
    if tech_key == "叠层":
        return min(0.5, max(0, (year - 2030) / 5.0))
    return 0.0


